const rendered=renderText('### A heading\nA paragraph\n* First\n* Second\n\n1. One\n2. Two');
assert.match(rendered,/<h3>A heading<\/h3>/);
assert.match(rendered,/<ul><li>First<\/li><li>Second<\/li><\/ul>/);
assert.match(rendered,/<ol start="1">/);
assert.match(renderText('| Term | Meaning |\n| --- | --- |\n| X | Flip |'),/<table>/);
assert.match(renderText('Step 1: Initial state. Step 2: Apply X.'),/<strong>Step 2:<\/strong>/);
const stepHeadings=renderText('### Step 1: State the rule\nUse the rule.\n\n### Step 2: Apply it\nUse the result of Step 1. This stays in the same paragraph.');
assert.match(stepHeadings,/<h3>Step 1: State the rule<\/h3>/);
assert.match(stepHeadings,/<h3>Step 2: Apply it<\/h3>/);
assert.match(stepHeadings,/<p>Use the result of Step 1\. This stays in the same paragraph\.<\/p>/);
assert.doesNotMatch(stepHeadings,/<p>#{1,6}<\/p>/);
assert.match(renderText('```text\nStep 1: A. Step 2: B.\n```'),/<pre><code>Step 1: A\. Step 2: B\.<\/code><\/pre>/);
assert.match(renderText('Step 1: Read `Step 2: literal`. Step 2: Continue.'),/<code>Step 2: literal<\/code>/);
assert.equal(sourceText('\uf0d8 \uf0de \uf0d9 \uf0da \uf0db \uf022 \uf024'),'¬ ⇒ ∧ ∨ ⇔ ∀ ∃');
assert.equal(sourceText('∧ ∃ □ \ue123'),'∧ ∃ □ \ue123');
const sourceBullets=renderSourceText('\uf06e A predicate has terms. \uf06e Quantifiers \uf022, \uf024');
assert.match(sourceBullets,/<ul><li>A predicate has terms\.<\/li><li>Quantifiers ∀, ∃<\/li><\/ul>/);
assert.match(renderSourceText('\uf06e A wrapped sentence\ncontinues here.\n\uf06e Next point.'),/<li>A wrapped sentence continues here\.<\/li><li>Next point\.<\/li>/);
assert.doesNotMatch(renderSourceText('\uf06e <script>unsafe()</script>'),/<script>/);
assert.match(renderText('\uf06e literal private character'),/\uf06e/);
assert.match(renderText('\\[\\frac{1}{\\sqrt{2}}\\begin{pmatrix}1\\\\1\\end{pmatrix}\\]'),/katex-display/);
assert.match(inlineText('State \\( |\\psi\\rangle \\)'),/katex/);
for(const text of ['<img src=x onerror=alert(1)>','**<script>evil()</script>**','`<iframe>`']){
  assert.doesNotMatch(renderText(text),/<(?:img|script|iframe)/);
}
assert.doesNotMatch(inlineText('\\(\\href{javascript:alert(1)}{click}\\)'),/href="javascript:/);

